"""
CLI Entry point for ArcCW to ARC9 Converter
"""
import argparse
import sys
from pathlib import Path
from typing import Optional

from .addon_converter import AddonConverter
from .weapon_converter import WeaponConverter
from .attachment_converter import AttachmentConverter
from .bulk_converter import BulkConverter, detect_arccw_addons

BANNER = r"""==================================================
ArcCW to ARC9 Converter v1.0.0
Converting Arctic's Custom Weapons to ARC9 for Garry's Mod
=================================================="""

def main():
    if "--gui" in sys.argv:
        from .gui import launch_gui
        launch_gui()
        return

    print(BANNER)
    parser = argparse.ArgumentParser(
        description="Convert Garry's Mod ArcCW weapons and addons to ARC9 format."
    )
    parser.add_argument(
        "input",
        type=str,
        nargs="?",
        default=None,
        help="Path to an ArcCW addon directory or a single ArcCW SWEP / attachment Lua file."
    )
    parser.add_argument(
        "-o", "--output",
        type=str,
        default=None,
        help="Destination directory or file path (optional, auto-generated by default)."
    )
    parser.add_argument(
        "--bulk",
        nargs="+",
        help="Convert multiple ArcCW addon directories in batch mode."
    )
    parser.add_argument(
        "--scan",
        type=str,
        default=None,
        help="Scan a parent directory (e.g. garrysmod/addons) and batch convert all discovered ArcCW addons."
    )
    parser.add_argument(
        "--gui",
        action="store_true",
        help="Launch the Graphical User Interface."
    )
    parser.add_argument(
        "--no-bulk",
        action="store_true",
        help="Disable bulk attachment file bundling (output separate attachment files in lua/arc9/common/attachments/)."
    )
    parser.add_argument(
        "--no-assets",
        action="store_true",
        help="Skip copying asset directories (models, materials, sound, particles)."
    )
    parser.add_argument(
        "--att-id",
        type=str,
        default=None,
        help="Explicit attachment ID when converting a single standalone attachment file."
    )

    args = parser.parse_args()

    # Case A: Scan mode
    if args.scan:
        scan_dir = Path(args.scan).resolve()
        print(f"[*] Scanning for ArcCW addons in: {scan_dir}")
        found = detect_arccw_addons(scan_dir)
        if not found:
            print(f"[!] No ArcCW addons found in {scan_dir}")
            sys.exit(0)
        print(f"[+] Found {len(found)} addon(s):")
        for a in found:
            print(f"    - {a.name} ({a})")

        bulk_conv = BulkConverter(
            items=found,
            output_parent_dir=args.output,
            bulk_attachments=not args.no_bulk,
            copy_assets=not args.no_assets,
            log_callback=print
        )
        bulk_conv.convert()
        return

    # Case B: Bulk mode with explicit paths
    if args.bulk:
        items = [Path(p).resolve() for p in args.bulk]
        bulk_conv = BulkConverter(
            items=items,
            output_parent_dir=args.output,
            bulk_attachments=not args.no_bulk,
            copy_assets=not args.no_assets,
            log_callback=print
        )
        bulk_conv.convert()
        return

    # If no input provided, show help
    if not args.input:
        parser.print_help()
        sys.exit(1)

    input_path = Path(args.input).resolve()

    if not input_path.exists():
        print(f"[ERROR] Input path does not exist: {input_path}")
        sys.exit(1)

    # Case 1: Directory (Addon or Lua tree)
    if input_path.is_dir():
        print(f"[*] Processing addon directory: {input_path}")
        converter = AddonConverter(
            input_dir=input_path,
            output_dir=args.output,
            bulk_attachments=not args.no_bulk,
            copy_assets=not args.no_assets
        )
        print(f"[*] Output directory set to: {converter.output_dir}")
        report = converter.convert()

        print("\n[+] Conversion Report:")
        print(f"  - Weapons converted: {len(report['weapons'])}")
        for w in report["weapons"]:
            print(f"    * {w['source']} -> {w['destination']}")

        print(f"  - Attachments converted: {len(report['attachments'])}")
        for a in report["attachments"]:
            print(f"    * {a['source']} ({a['att_id']}) [{a['mode']}]")

        print(f"  - Asset directories copied: {', '.join(report['copied_dirs'])}")

        if report["warnings"]:
            print("\n[!] Warnings:")
            for warn in report["warnings"]:
                print(f"    * {warn}")

        print(f"\n[SUCCESS] Finished converting {input_path.name} to {converter.output_dir.name}.\n")

    # Case 2: Single file
    elif input_path.is_file():
        content = input_path.read_text(encoding="utf-8", errors="replace")
        # Detect whether it is an attachment or weapon
        is_att = "att.PrintName" in content or "att.Slot" in content or "attachments" in str(input_path).lower()

        if is_att:
            att_id = args.att_id or input_path.stem
            print(f"[*] Detected attachment file: {input_path.name} (ID: {att_id})")
            ac = AttachmentConverter(content, att_id)
            res = ac.convert(is_bulk=False)

            if args.output:
                out_path = Path(args.output).resolve()
            else:
                out_path = input_path.parent / f"arc9_{input_path.name}"

            out_path.write_text(res, encoding="utf-8")
            print(f"[+] Converted attachment saved to: {out_path}")

        else:
            print(f"[*] Detected weapon file: {input_path.name}")
            wc = WeaponConverter(content, filename=input_path.name)
            res = wc.convert()

            if args.output:
                out_path = Path(args.output).resolve()
            else:
                out_name = input_path.name.replace("arccw_", "arc9_")
                if out_name == input_path.name:
                    out_name = f"arc9_{input_path.name}"
                out_path = input_path.parent / out_name

            out_path.write_text(res, encoding="utf-8")
            print(f"[+] Converted weapon saved to: {out_path}")

        print(f"[SUCCESS] Conversion complete.\n")

if __name__ == "__main__":
    main()
